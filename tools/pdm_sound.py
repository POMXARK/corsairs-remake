#!/usr/bin/env python3
"""Converts the sounds and the music of the original Sea Dogs (PDM 1.061).

The original (ENGINE.exe, land_sector.dll) plays them by aliases:
  MUSIC/mmusic.ini        "alias,file": Resource\\Music\\<file>.mp3 (an MP3 in a RIFF WAVE wrapper)
  SOUNDS/msound.ini       "alias,file,count": Resource\\Sounds\\<file>.wav, or with count > 1 one of
                          <file>0.wav .. <file><count-1>.wav at random
  WORLDS/nations.idf      town_music: the music alias of the towns of a nation (eTown, sTown ...)
  WORLDS/locations/snd/*.snd   the sounds of a kind of location (the sound line of a .loc), 14 lines:
                          hero steps L/R, man steps L/R, girl steps L/R, the ambient loop by day and
                          by night, a periodic sound by day and its interval in ms, the same by night,
                          the voice of one character and the voices of many ("null": none)

Writes, for the sound service of the engine (names lower case, the service looks aliases up exactly):
  resource/sounds/pdm/*.wav             every wav of SOUNDS
  resource/sounds/pdm/music/*.mp3       every mp3 of MUSIC, without the RIFF wrapper
  resource/ini/aliases/pdm.ini          an alias per line of msound.ini
  resource/ini/sound_scheme.ini         pdm_<kind>_day/_night: the periodic sound and the single voice
  program/data/pdm_sound.c              PdmMusic.<alias> = file, PdmLocSounds.<kind>.{day, night,
                                        period, interval, single, many, scheme}, PdmSound_Init()

usage: pdm_sound.py <PDM_dir> <game_dir>
"""
import shutil
import struct
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
from pdm_ship import index_files  # noqa: E402

# the lines of a .snd (WORLDS/locations/snd/format) that the scripts use
SND_KEYS = {6: "day", 7: "night", 8: "period", 9: "interval", 10: "night_period", 11: "night_interval",
            12: "single", 13: "many"}


def entries(path: Path):
    """The comma-separated lines of an .ini of the original, without the ; comments."""
    for line in path.read_text(encoding="cp1251").splitlines():
        line = line.split(";", 1)[0].strip()
        if line:
            yield [f.strip() for f in line.split(",")]


def unwrap_mp3(data: bytes) -> bytes:
    """The data chunk of a RIFF WAVE holding MP3 (format 0x55); anything else as it is."""
    if data[:4] != b"RIFF" or data[8:12] != b"WAVE":
        return data
    at = 12
    while at + 8 <= len(data):
        tag, size = data[at:at + 4], struct.unpack_from("<I", data, at + 4)[0]
        if tag == b"data":
            return data[at + 8:at + 8 + size]
        at += 8 + size + (size & 1)
    return data


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        sys.exit(1)
    res = Path(sys.argv[1])
    res = res / "RESOURCE" if (res / "RESOURCE").is_dir() else res
    game = Path(sys.argv[2])
    sounds, music_dir = game / "resource/sounds/pdm", game / "resource/sounds/pdm/music"
    music_dir.mkdir(parents=True, exist_ok=True)
    (game / "resource/ini/aliases").mkdir(parents=True, exist_ok=True)

    # "folder\\file" in any case -> the wav (msound.ini names files of the subfolders too)
    wavs = {f.relative_to(res / "SOUNDS").with_suffix("").as_posix().lower(): f
            for f in (res / "SOUNDS").rglob("*") if f.suffix.lower() == ".wav"}

    aliases, missing, seen = [], [], set()
    for fields in entries(res / "SOUNDS" / "msound.ini"):
        if len(fields) < 2:
            continue
        name, stem = fields[0].lower(), fields[1]
        count = int(fields[2]) if len(fields) > 2 and fields[2].isdigit() else 1
        files = [stem] if count == 1 else [f"{stem}{i}" for i in range(count)]
        files = [f.replace("\\", "/").lower() for f in files]
        found = [f for f in files if f in wavs]
        missing += [f for f in files if f not in wavs]
        if found and name not in seen:
            seen.add(name)
            for f in found:
                (sounds / f).parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(wavs[f], sounds / f"{f}.wav")
            paths = ["pdm\\" + f.replace("/", "\\") + ".wav" for f in found]
            aliases.append(f"[{name}]\n" + "".join(f"name = {p}, 1.0\n" for p in paths)
                           + "minDistance = 2.0\nmaxDistance = 40.0\nvolume = 1.0\n")
    (game / "resource/ini/aliases/pdm.ini").write_text(
        "; generated by tools/pdm_sound.py from SOUNDS/msound.ini of the original\n\n" + "\n".join(aliases),
        encoding="utf-8")

    mp3s = index_files(res / "MUSIC")
    lines = []
    for fields in entries(res / "MUSIC" / "mmusic.ini"):
        if len(fields) < 2 or fields[1].lower() not in mp3s:
            continue
        name = mp3s[fields[1].lower()].stem.lower() + ".mp3"
        (music_dir / name).write_bytes(unwrap_mp3(mp3s[fields[1].lower()].read_bytes()))
        lines.append(f'\tPdmMusic.{fields[0].lower()} = "pdm\\music\\{name}";')

    kinds, schemes = 0, []
    for snd in sorted((res / "WORLDS" / "locations" / "snd").glob("*.snd")):
        values = [v.strip() for v in snd.read_text(encoding="cp1251").splitlines()]
        kind = snd.stem.lower()
        for i, key in SND_KEYS.items():
            v = values[i].lower() if i < len(values) else "null"
            # "nill" in DeadTown.snd is a typo of null
            lines.append(f'\tPdmLocSounds.{kind}.{key} = "{"" if v in ("null", "nill") else v}";')
        lines.append(f'\tPdmLocSounds.{kind}.scheme = "pdm_{kind}_day";')
        kinds += 1
        # what sounds now and then: the periodic sound of the day about once in its interval, the voice
        # of a visitor every few seconds
        day = dict(zip(SND_KEYS.values(), (values[i].lower() for i in SND_KEYS)))
        for when in ("day", "night"):
            prefix = "" if when == "day" else "night_"
            channels = []
            if day[prefix + "period"] not in ("null", "nill"):
                ms = int(day[prefix + "interval"])
                channels.append(f"ch = {day[prefix + 'period']}, {ms // 2000}, {ms * 3 // 2000}, 1.0")
            if day["single"] != "null":
                channels.append(f"ch = {day['single']}, 4, 12, 0.8")
            schemes.append(f"[pdm_{kind}_{when}]\n" + "".join(c + "\n" for c in channels))

    (game / "resource/ini/sound_scheme.ini").write_text(
        "; generated by tools/pdm_sound.py from WORLDS/locations/snd of the original: pdm_<kind>_<day|night>\n\n"
        + "\n".join(schemes), encoding="utf-8")
    (game / "program/data/pdm_sound.c").write_text(
        "// generated by tools/pdm_sound.py from MUSIC/mmusic.ini and WORLDS/locations/snd of the original\n"
        "object PdmMusic;\nobject PdmLocSounds;\n\nvoid PdmSound_Init()\n{\n" + "\n".join(lines) + "\n}\n",
        encoding="utf-8")
    print(f"pdm_sound: {len(aliases)} aliases, {len(lines) - 9 * kinds} pieces of music, {kinds} kinds of location"
          + (f", {len(missing)} files missing (the voices of the characters are pdm_ui.py's)" if missing else ""))


if __name__ == "__main__":
    main()
