#!/usr/bin/env python3
"""Encounters of the world map: RESOURCE/INI/mapparam.ini of the original (MAP.dll LoadPatterns, MapSailAndEvent) and
the texts of the encounters from RESOURCE/TEXTS/RUSSIAN/INI/interface.ini.

program/data/pdm_encounters.c, PdmEncounters_Init():
  PdmPattern.p<n>.{mc,mu,md,wc,wu,wd}  [MapPatterns] pattern<n> = merchants, up class, down class, warships, up class, down class
  PdmEncGrid.n<nation>.c<col>_<row>    [Pattern<Nation>] mapN: the pattern number in the cell of the map (20 columns by 15 rows of
                                       60 px); nation 0 england, 1 pirate, 2 france, 3 spain (nations.idf); empty cells are not written
  PdmEncIsland.r<dy>_<dx>              [PatternIsland] the pattern round an island cell, dy and dx from 0 to 4 (the island at 2_2)
  PdmEncText.<key>                     the texts of the encounters (%s and %d are filled by encounter.c)
Running it again gives the same file.

usage: pdm_encounters.py <original game dir> <pdm-game dir>
"""
import re
import sys
from pathlib import Path

NATIONS = ["England", "Pirate", "France", "Spain"]
TEXT_KEYS = re.compile(r"^(months|Mapparammessage\d+|MapMessageShips|MapMessageAttack|MapMessageWAR|MapMessage(NotEnoughMoney|Reputation[0-6]?|Bunt|WeekMoney|Tornado)|t_MapFleet|attack\d+|mapships_\d+|"
                       r"pattern\d+|map(English|Pirates|French|Spanish)1?|MapparamIslandNoNation|mapEngland|mapPirate|mapFrance|mapSpain|Mapparam(Untilsunrise|Untilsunset|Oneday|Twodays|Threedays|Untilencounter)|lbMapOK|lbMapEngage|lbMapIgnore)$")


def find(game: Path, *parts):
    cur = game
    for part in parts:
        cur = next((p for p in cur.iterdir() if p.name.lower() == part.lower()), None)
        if cur is None:
            sys.exit("not found: " + "/".join(parts))
    return cur


def sections(text: str):
    out, cur = {}, None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("[") and line.endswith("]"):
            cur = out.setdefault(line[1:-1], [])
        elif cur is not None and line and not line.startswith("//") and not line.startswith(";"):
            cur.append(line)
    return out


def pairs(lines):
    for line in lines:
        k, sep, v = line.partition("=")
        if sep:
            yield k.strip(), v.split("//")[0].strip()


def numbers(value: str):
    return [int(x) for x in value.split(",") if x.strip()]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    game, dst = Path(sys.argv[1]), Path(sys.argv[2])
    ini = sections(find(game, "RESOURCE", "INI", "mapparam.ini").read_bytes().decode("cp1251"))
    texts = find(game, "RESOURCE", "TEXTS", "RUSSIAN", "INI", "interface.ini").read_bytes().decode("cp1251").splitlines()
    out = ["// Generated by tools/pdm_encounters.py from mapparam.ini and interface.ini of the original. Do not edit.", "",
           "object PdmPattern;", "object PdmEncGrid;", "object PdmEncIsland;", "object PdmEncText;", "", "void PdmEncounters_Init()", "{"]
    patterns = 0
    for k, v in pairs(ini.get("MapPatterns", [])):
        m = re.fullmatch(r"pattern(\d+)", k)
        n = numbers(v)
        if m and len(n) == 6:
            for name, value in zip(("mc", "mu", "md", "wc", "wu", "wd"), n):
                out.append(f'\tPdmPattern.p{m[1]}.{name} = "{value}";')
            patterns += 1
    cells = 0
    for nation, name in enumerate(NATIONS):
        for k, v in pairs(ini.get("Pattern" + name, [])):
            m = re.fullmatch(r"map(\d+)", k)
            if not m:
                continue
            for col, value in enumerate(numbers(v)):
                if value:
                    out.append(f'\tPdmEncGrid.n{nation}.c{col}_{m[1]} = "{value}";')
                    cells += 1
    for k, v in pairs(ini.get("PatternIsland", [])):
        m = re.fullmatch(r"map(\d+)", k)
        if m:
            for dx, value in enumerate(numbers(v)):
                out.append(f'\tPdmEncIsland.r{m[1]}_{dx} = "{value}";')
    count = 0
    for line in texts:
        k, sep, v = line.partition("=")
        k = k.strip()
        if sep and TEXT_KEYS.match(k):
            out.append(f'\tPdmEncText.{k} = "{v.strip().replace(chr(34), chr(39))}";')
            count += 1
    out += [f'\tTrace("PDM encounters: {patterns} patterns, {cells} cells, {count} texts");', "}", ""]
    path = dst / "program" / "data" / "pdm_encounters.c"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"{path}: {patterns} patterns, {cells} cells, {count} texts")


if __name__ == "__main__":
    main()
