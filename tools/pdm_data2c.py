#!/usr/bin/env python3
"""Writes the game data of the original Sea Dogs (the JSON of pdm2storm.py) as Storm scripts.

The Storm script language reads no files, so the tables and cards become functions that fill
attributes of objects: program/data/pdm_data.c defines PdmShipTypes, PdmIslands, PdmNations,
PdmGoods, PdmTowns, PdmCharacters, PdmShips and PdmData_Init(), which main.c calls once.

Attribute names are identifiers in the script, so every record gets a key made of its name
(letters, digits, "_"); the name as it was stays in the .id attribute. Script strings have no
escapes, so '"' becomes "'".

usage: pdm_data2c.py <data_dir from pdm2storm.py> <program_dir>
"""
import json
import re
import sys
from pathlib import Path


def key(name: str, used: set) -> str:
    k = re.sub(r"[^A-Za-z0-9_]", "_", name.strip()) or "x"
    if not k[0].isalpha():
        k = "n" + k
    base, i = k, 2
    while k.lower() in used:
        k = f"{base}_{i}"
        i += 1
    used.add(k.lower())
    return k


def value(v) -> str:
    return '"' + str(v).replace('"', "'").replace("\n", " ") + '"'


class Writer:
    def __init__(self):
        self.lines = []

    def record(self, obj: str, rec_key: str, fields: dict):
        """obj.rec_key.field = "value"; nested dicts become nested attributes."""
        def put(path, d):
            for f, v in d.items():
                if v is None or not str(f).strip():
                    continue
                fk = re.sub(r"[^A-Za-z0-9_]", "_", str(f))
                if not fk[0].isalpha():
                    fk = "n" + fk
                if isinstance(v, dict):
                    put(f"{path}.{fk}", v)
                elif isinstance(v, list):
                    self.lines.append(f"\t{path}.{fk} = {value(','.join(map(str, v)))};")
                else:
                    self.lines.append(f"\t{path}.{fk} = {value(v)};")
        put(f"{obj}.{rec_key}", fields)

    def function(self, name: str, body_lines: list):
        return [f"void {name}()", "{"] + body_lines + ["}", ""]


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def table(data: Path, name: str):
    """WORLDS/<name>.idf: a list of objects, each a list of (field, value)."""
    return [dict(o) for o in load(data / "tables" / "WORLDS" / f"{name}.json")["objects"]]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    data, program = Path(sys.argv[1]), Path(sys.argv[2])
    out = []
    counts = {}
    functions = []

    def emit(obj, records, fn):
        """records: (key source, fields) pairs."""
        w, used = Writer(), set()
        for src, fields in records:
            k = key(src, used)
            w.record(obj, k, {"id": src, **fields})
        out.extend(w.function(fn, w.lines))
        functions.append(fn)
        counts[obj] = len(records)

    # Ships.idf has no unique names (all are "1".."7", the rating): the hull file is the key
    ship_types = table(data, "Ships")
    for t in ship_types:  # VFrigat: speedrate "10,8", a decimal comma that stf() would cut to 10
        t["speedrate"] = t["speedrate"].replace(",", ".")
    emit("PdmShipTypes", [(t["filename"].lower(), t) for t in ship_types], "PdmData_ShipTypes")
    # islands_x.idf is the map of the release (29 objects; Islands.idf is an older one of 11)
    emit("PdmIslands", [(t["name"], t) for t in table(data, "islands_x")], "PdmData_Islands")
    for name in ("nations", "Goods", "Towns", "Cannons", "Items", "relations"):
        emit("Pdm" + name.capitalize(), [(t["name"], t) for t in table(data, name)], "PdmData_" + name.capitalize())

    # the references are resolved here, the script has no lower-case function: a ship gets the key
    # of its type (.shp class = Ships.idf filename), a character the key of its ship
    ships = [load(f) for f in sorted((data / "ships" / "SHIPS").glob("*.json"))]
    ship_keys, used = {}, set()
    for s in ships:
        ship_keys[s["source"].lower()] = key(Path(s["source"]).stem, used)
    emit("PdmShips", [(Path(s["source"]).stem, {**{k: v for k, v in s.items() if k != "unknown"},
                                                "type_key": s["class"].lower()}) for s in ships],
         "PdmData_Ships")
    chars = [load(f) for f in sorted((data / "characters" / "CHARACTERS").glob("*.json"))]
    emit("PdmCharacters", [(c["id"], {**{k: v for k, v in c.items() if k not in ("unknown", "id")},
                                      "ship_key": ship_keys.get((c.get("ship") or "").lower(), "")}) for c in chars],
         "PdmData_Characters")

    # the story data is interpreted by later stages; here only its size, to check the load
    story = {name: len(list((data / name).rglob("*.json"))) for name in ("actions", "quests", "dialogs")}

    objects = sorted(counts)
    head = ["// Generated by tools/pdm_data2c.py from the data of the original Sea Dogs. Do not edit.", ""]
    head += [f"object {o};" for o in objects] + [""]
    init = [f"\t{fn}();" for fn in functions]
    summary = ", ".join(f"{o} {counts[o]}" for o in objects) + ", " + ", ".join(f"{k} {v}" for k, v in story.items())
    init.append(f'\tTrace("PDM data: {summary}");')
    head += ["void PdmData_Init()", "{"] + init + ["}", ""]
    dst = program / "data" / "pdm_data.c"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(head + out), encoding="utf-8")
    print(f"{dst}: {summary}")


if __name__ == "__main__":
    main()
