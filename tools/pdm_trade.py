#!/usr/bin/env python3
"""What each island exports, imports and forbids in its stores: RESOURCE/IMAGES/GOODS/ISLANDS/<island>.gst of the
original (TOWN.dll reads <island>.gst when the store is opened: "+Goods" export, "-Goods" import, "!Goods" contraband,
the names are the names of Goods.idf compared without case; a name that is no goods, like "Wood", does nothing).

program/data/pdm_trade.c: PdmTrade.<island key>.<goods key> = "export" | "import" | "contraband" and PdmTrade_Init().
The ships a shipyard sells are in <island>.sht next to it (one type file name per line, TOWN.dll reads it when the shipyard
is opened): PdmYard.<island key>.<type> = "1", filled in the same PdmTrade_Init(). An island without .sht has no rows.
The keys are the ones pdm_data2c.py makes (PdmIslands, PdmGoods). The islands without a .gst have no rows.
Running it again gives the same file.

usage: pdm_trade.py <original game dir> <pdm-game dir>
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pdm_data2c import key, table  # noqa: E402

# the file of the island is named after the model, not always after islands_x.idf (Omory is omori.gst)
ALIASES = {"omori": "omory"}
KINDS = {"+": "export", "-": "import", "!": "contraband"}


def read_gst(path: Path):
    rows = []
    for line in path.read_bytes().decode("cp1251").splitlines():
        line = line.strip()
        if line[:1] in KINDS and len(line) > 1:
            rows.append((line[1:].strip().lower(), KINDS[line[0]]))
    return rows


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    game, dst = Path(sys.argv[1]), Path(sys.argv[2])
    folder = next((p for p in (game / "RESOURCE" / "IMAGES" / "GOODS" / "ISLANDS", game / "resource" / "images" / "goods" / "islands") if p.is_dir()), None)
    if folder is None:
        sys.exit("no IMAGES/GOODS/ISLANDS in " + str(game))
    files = {}
    for f in sorted(folder.glob("*.gst")):
        stem = ALIASES.get(f.stem.lower(), f.stem.lower())
        if stem != "all":  # all.gst is the older list of 10 islands in one file
            files[stem.replace(" ", "")] = f
    yards = {}
    for f in sorted(folder.glob("*.sht")):
        yards[re.sub(r"[^a-z]", "", ALIASES.get(f.stem.lower(), f.stem.lower()))] = f
    goods = {}
    used = set()
    for t in table(dst / "data", "Goods"):
        goods[t["name"].lower()] = key(t["name"], used)
    lines, used, count = [], set(), 0
    for isl in table(dst / "data", "islands_x"):
        k = key(isl["name"], used)
        stem = re.sub(r"[^a-z]", "", isl["name"].lower().rstrip("_"))
        ysrc = yards.get(stem)
        if ysrc is not None:
            for line in ysrc.read_bytes().decode("cp1251").splitlines():
                name = re.sub(r"[^a-z0-9_]", "", line.strip().lower())
                if name:
                    lines.append(f'\tPdmYard.{k}.{name} = "1";')
        src = next((f for s, f in files.items() if re.sub(r"[^a-z]", "", s) == stem), None)
        if src is None:
            continue
        for name, kind in read_gst(src):
            if name in goods:
                lines.append(f'\tPdmTrade.{k}.{goods[name]} = "{kind}";')
        count += 1
    out = ["// Generated by tools/pdm_trade.py from IMAGES/GOODS/ISLANDS/*.gst of the original. Do not edit.", "",
           "object PdmTrade;", "object PdmYard;", "", "void PdmTrade_Init()", "{"] + lines + [f'\tTrace("PDM trade: {count} islands with lists");', "}", ""]
    path = dst / "program" / "data" / "pdm_trade.c"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"{path}: {count} islands, {len(lines)} rows")


if __name__ == "__main__":
    main()
